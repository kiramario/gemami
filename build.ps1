# ============================================================
#  Gemini Build Script - 打包为 EXE
#  用法: .\build.ps1 [-OutputDir <path>]
# ============================================================
param(
    [string]$OutputDir = (Join-Path $PSScriptRoot "Release")
)

$ErrorActionPreference = "Stop"
$ScriptDir = $PSScriptRoot

# ---------- 检查并安装 ps2exe ----------
function Ensure-ps2exe {
    if (-not (Get-Module -ListAvailable -Name ps2exe)) {
        Write-Host "[*] ps2exe not installed, installing..." -ForegroundColor Yellow
        try {
            Install-Module -Name ps2exe -Force -Scope CurrentUser -AllowClobber
            Import-Module ps2exe -Force
            Write-Host "[+] ps2exe installed" -ForegroundColor Green
        }
        catch {
            Write-Error "Failed to install ps2exe: $($_.Exception.Message)"
            Write-Host "Please install manually: Install-Module -Name ps2exe -Scope CurrentUser" -ForegroundColor Yellow
            exit 1
        }
    }
    else {
        Import-Module ps2exe -Force
        Write-Host "[+] ps2exe ready" -ForegroundColor Green
    }
}

# ---------- Base64 编码文件 ----------
function Get-Base64FromFile {
    param([string]$Path)
    if (-not (Test-Path $Path)) {
        Write-Error "File not found: $Path"
        return $null
    }
    $bytes = [System.IO.File]::ReadAllBytes((Resolve-Path $Path))
    return [Convert]::ToBase64String($bytes)
}

# ---------- 生成独立脚本 ----------
function New-StandaloneScript {
    Write-Host ""
    Write-Host "========================================" -ForegroundColor Cyan
    Write-Host "  Step 1: Generate standalone script" -ForegroundColor Cyan
    Write-Host "========================================" -ForegroundColor Cyan
    Write-Host ""

    # 读取并 Base64 编码所有资源
    Write-Host "[*] Encoding Main.xaml..." -ForegroundColor Yellow
    $xamlB64 = Get-Base64FromFile -Path (Join-Path $ScriptDir "Main.xaml")

    Write-Host "[*] Encoding Config/tools.json..." -ForegroundColor Yellow
    $jsonB64 = Get-Base64FromFile -Path (Join-Path $ScriptDir "Config\tools.json")

    Write-Host "[*] Encoding tool scripts..." -ForegroundColor Yellow
    $toolEntries = @()
    Get-ChildItem (Join-Path $ScriptDir "Tools\*.ps1") | ForEach-Object {
        $b64 = Get-Base64FromFile -Path $_.FullName
        $toolEntries += "        '$($_.Name)' = '$b64'"
        Write-Host "    - $($_.Name)" -ForegroundColor Gray
    }

    # 读取原始 Main.ps1
    $mainScript = Get-Content (Join-Path $ScriptDir "Main.ps1") -Raw -Encoding UTF8

    # ====== 构建嵌入资源的替换 ======
    
    # 1) 用占位标记插入 Base64 资源变量
    $placeholder = "# <BUILD_EMBED_RESOURCES>"

    # 用 StringBuilder 构建资源块（避免 here-string 展开问题）
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("# ====== Embedded resources (base64, auto-generated by build.ps1) ======")
    [void]$sb.AppendLine('$script:EmbeddedXamlB64 = ''' + $xamlB64 + '''')
    [void]$sb.AppendLine('$script:EmbeddedConfigB64 = ''' + $jsonB64 + '''')
    [void]$sb.AppendLine('$script:EmbeddedToolsB64 = @{')
    foreach ($entry in $toolEntries) {
        [void]$sb.AppendLine("    " + $entry)
    }
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine("# ====== End embedded resources =====")

    $resourceBlock = $sb.ToString()
    $mainScript = $mainScript.Replace($placeholder, $resourceBlock)

    # 2) 替换 Load-Xaml 函数
    $loadXamlOld = @'
function Load-Xaml {
    param([string]$Path)
    
    $xamlContent = Get-Content -Path $Path -Encoding UTF8 -Raw
    
    # 处理 XAML 中全局引用
    $reader = [System.Xml.XmlNodeReader]::new([xml]$xamlContent)
    $window = [Windows.Markup.XamlReader]::Load($reader)
    
    return $window
}
'@
    $loadXamlNew = @'
function Load-Xaml {
    # Decode embedded base64 XAML
    $xamlBytes = [Convert]::FromBase64String($script:EmbeddedXamlB64)
    $xamlContent = [System.Text.Encoding]::UTF8.GetString($xamlBytes)

    # Process XAML
    $reader = [System.Xml.XmlNodeReader]::new([xml]$xamlContent)
    $window = [Windows.Markup.XamlReader]::Load($reader)

    return $window
}
'@
    $mainScript = $mainScript.Replace($loadXamlOld, $loadXamlNew)

    # 3) 替换 Load-ToolConfigs 函数
    $loadConfigOld = @'
function Load-ToolConfigs {
    if (-not (Test-Path $script:ConfigPath)) {
        Write-Error "配置文件不存在: $script:ConfigPath"
        return $null
    }
    $json = Get-Content -Path $script:ConfigPath -Encoding UTF8 -Raw
    return $json | ConvertFrom-Json
}
'@
    $loadConfigNew = @'
function Load-ToolConfigs {
    # Decode embedded base64 JSON config
    if (-not $script:EmbeddedConfigB64) {
        Write-Error "Embedded config is empty"
        return $null
    }
    $jsonBytes = [Convert]::FromBase64String($script:EmbeddedConfigB64)
    $json = [System.Text.Encoding]::UTF8.GetString($jsonBytes)
    return $json | ConvertFrom-Json
}
'@
    $mainScript = $mainScript.Replace($loadConfigOld, $loadConfigNew)

    # 4) 替换 Select-Tool 中的工具脚本加载逻辑
    $selectToolOld = @'
    # 加载工具脚本
    $scriptPath = Join-Path $script:ToolsDir $ToolConfig.Script
    if (-not (Test-Path $scriptPath)) {
        Write-Log "错误: 工具脚本不存在 - $scriptPath" -Type Error
        return
    }
    
    try {
        # 动态执行工具脚本，脚本内部通过 $Global:MainWindow 获取窗口引用
        # 脚本应返回一个 UIElement 或定义自己的 UI
        $result = . $scriptPath
'@
    $selectToolNew = @'
    # Decode and execute embedded tool script
    if (-not $script:EmbeddedToolsB64.ContainsKey($ToolConfig.Script)) {
        Write-Log "Error: Tool script not embedded - $($ToolConfig.Script)" -Type Error
        return
    }

    try {
        $scriptBytes = [Convert]::FromBase64String($script:EmbeddedToolsB64[$ToolConfig.Script])
        $scriptContent = [System.Text.Encoding]::UTF8.GetString($scriptBytes)
        $result = . ([ScriptBlock]::Create($scriptContent))
'@
    $mainScript = $mainScript.Replace($selectToolOld, $selectToolNew)

    # 5) 替换 Main 函数中 XAML 加载调用
    $mainCheckOld = @'
    # 加载 XAML
    if (-not (Test-Path $script:XamlPath)) {
        Write-Host "错误: XAML 文件不存在 - $script:XamlPath" -ForegroundColor Red
        return
    }
    
    $window = Load-Xaml -Path $script:XamlPath
'@
    $mainCheckNew = @'
    # Load embedded XAML
    $window = Load-Xaml
'@
    $mainScript = $mainScript.Replace($mainCheckOld, $mainCheckNew)

    # 写入独立脚本
    $standalonePath = Join-Path $OutputDir "Gemini_Standalone.ps1"
    $null = New-Item -Path $OutputDir -ItemType Directory -Force
    $utf8Bom = [System.Text.UTF8Encoding]::new($true)
    [System.IO.File]::WriteAllText($standalonePath, $mainScript, $utf8Bom)

    # 验证语法
    Write-Host "[*] Validating standalone script syntax..." -ForegroundColor Yellow
    $errors = $null
    $null = [System.Management.Automation.Language.Parser]::ParseFile($standalonePath, [ref]$null, [ref]$errors)
    if ($errors.Count -gt 0) {
        Write-Host "[!] Syntax errors found:" -ForegroundColor Red
        $errors | ForEach-Object { Write-Host "    Line $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
        Write-Host ""
        Write-Host "[!] Build aborted. Check: $standalonePath" -ForegroundColor Red
        exit 1
    }

    $size = [math]::Round((Get-Item $standalonePath).Length / 1KB, 1)
    Write-Host "[+] Standalone script: $standalonePath" -ForegroundColor Green
    Write-Host "    Size: ${size} KB" -ForegroundColor Gray

    return $standalonePath
}

# ---------- 编译为 EXE ----------
function Compile-Exe {
    param([string]$StandalonePath)

    Write-Host ""
    Write-Host "========================================" -ForegroundColor Cyan
    Write-Host "  Step 2: Compile to EXE" -ForegroundColor Cyan
    Write-Host "========================================" -ForegroundColor Cyan
    Write-Host ""

    $exePath = Join-Path $OutputDir "Gemini.exe"

    Write-Host "[*] Compiling..." -ForegroundColor Yellow

    try {
        Invoke-ps2exe -inputFile $StandalonePath `
                      -outputFile $exePath `
                      -title "Gemini" `
                      -noConsole `
                      -noError `
                      -requireAdmin:$false

        if (Test-Path $exePath) {
            $size = [math]::Round((Get-Item $exePath).Length / 1MB, 2)
            Write-Host ""
            Write-Host "========================================" -ForegroundColor Green
            Write-Host "  Build complete!" -ForegroundColor Green
            Write-Host "========================================" -ForegroundColor Green
            Write-Host "  Output: $exePath" -ForegroundColor White
            Write-Host "  Size:   ${size} MB" -ForegroundColor White
            Write-Host "========================================" -ForegroundColor Green
        }
        else {
            Write-Error "EXE not generated."
        }
    }
    catch {
        Write-Error "Compilation failed: $($_.Exception.Message)"
        exit 1
    }
}

# ---------- 清理 ----------
function Cleanup {
    param([string]$StandalonePath)
    Write-Host ""
    Write-Host "[*] Cleaning up temp files..." -ForegroundColor Yellow
    if (Test-Path $StandalonePath) {
        Remove-Item $StandalonePath -Force
        Write-Host "    Removed: $StandalonePath" -ForegroundColor Gray
    }
}

# ========== Main ==========
Write-Host ""
Write-Host "========================================" -ForegroundColor Cyan
Write-Host "  Gemini EXE Build Script" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host ""

# Step 0: Check dependencies
Ensure-ps2exe

# Step 1: Generate standalone script with embedded resources
$standalonePath = New-StandaloneScript

# Step 2: Compile with ps2exe
Compile-Exe -StandalonePath $standalonePath

# Step 3: Cleanup (uncomment to auto-delete temp file)
# Cleanup -StandalonePath $standalonePath

Write-Host ""
Write-Host "Output directory: $OutputDir" -ForegroundColor Cyan
Get-ChildItem $OutputDir -File | ForEach-Object {
    Write-Host "  $($_.Name)  ($([math]::Round($_.Length / 1KB, 1)) KB)" -ForegroundColor Gray
}
Write-Host ""
Write-Host "Run Gemini.exe to launch!" -ForegroundColor Green
